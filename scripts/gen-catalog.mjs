/**
 * Sinh src/lib/catalog.generated.ts — chỉ mục metadata nhẹ cho các trang danh sách.
 *
 * Vì sao: trang chủ và trang sách chỉ cần metadata (tiêu đề, cấp độ, thời lượng,
 * số câu) để hiển thị danh sách. Nạp toàn bộ nội dung (mọi câu, từ vựng, bản dịch)
 * vào bundle phía client từng khiến một chunk phình lên ~2MB. File này chỉ chứa
 * metadata (~vài chục KB), còn nội dung đầy đủ chỉ được nạp ở trang chi tiết
 * phía server (watch/read theo từng id).
 *
 * Thứ tự giữ đúng thứ tự đăng ký trong src/lib/content.ts (nguồn sự thật duy nhất).
 * Chạy tự động qua prebuild/predev; chạy tay: node scripts/gen-catalog.mjs
 */
import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const contentTs = readFileSync(join(root, "src/lib/content.ts"), "utf8");

function registeredIds(kind) {
  const re = new RegExp(`from "\\.\\./\\.\\./content/${kind}/([a-z0-9-]+)\\.json"`, "g");
  return [...contentTs.matchAll(re)].map((m) => m[1]);
}

function load(kind, id) {
  return JSON.parse(readFileSync(join(root, `content/${kind}/${id}.json`), "utf8"));
}

const videoIds = registeredIds("videos");
const storyIds = registeredIds("stories");

// Chặn lỗi: file JSON trên đĩa mà chưa đăng ký (hoặc ngược lại) phải lộ ra ngay.
for (const [kind, ids] of [["videos", videoIds], ["stories", storyIds]]) {
  const onDisk = readdirSync(join(root, `content/${kind}`))
    .filter((f) => f.endsWith(".json"))
    .map((f) => f.replace(/\.json$/, ""));
  const missing = onDisk.filter((id) => !ids.includes(id));
  const ghost = ids.filter((id) => !onDisk.includes(id));
  if (missing.length || ghost.length) {
    console.error(`gen-catalog: lệch đăng ký ở ${kind}: chưa đăng ký=${missing} | không có file=${ghost}`);
    process.exit(1);
  }
}

const videos = videoIds.map((id) => {
  const v = load("videos", id);
  return {
    id: v.id, youtubeId: v.youtubeId, titles: v.titles, level: v.level,
    category: v.category, durationSec: v.durationSec, free: v.free,
    lineCount: v.lines.length,
    // Đoạn học trong video (cùng công thức với src/lib/clip.ts)
    clipStart: v.lines.length ? Math.max(0, Math.floor(v.lines[0].start - 2)) : 0,
    clipEnd: v.lines.length ? Math.min(v.durationSec, Math.ceil(v.lines[v.lines.length - 1].end + 1.5)) : v.durationSec,
  };
});

const stories = storyIds.map((id) => {
  const s = load("stories", id);
  return {
    id: s.id, titles: s.titles, level: s.level, topic: s.topic,
    source: s.source, free: s.free, sentenceCount: s.sentences.length,
    ...(typeof s.cover === "string" && s.cover.startsWith("/covers/") ? { cover: s.cover } : {}),
    ...(s.series ? { series: s.series } : {}),
    ...(s.shelf ? { shelf: s.shelf } : {}),
    ...(s.origin ? { origin: s.origin } : {}),
    // Audio liền của chương (gói v2): trình phát tự chuyển chương khi tắt màn hình
    ...(s.audioTrack ? { audioTrack: s.audioTrack } : {}),
  };
});

const out = `/**
 * GENERATED by scripts/gen-catalog.mjs — KHÔNG sửa tay.
 * Chỉ mục metadata nhẹ cho trang danh sách; nội dung đầy đủ nằm ở content.ts.
 */
import type { AudioTrack, JlptLevel, StoryContent, Translations, VideoCategory } from "./content-schema";

export interface VideoIndexItem {
  id: string;
  youtubeId: string;
  titles: Translations;
  level: JlptLevel;
  category: VideoCategory;
  durationSec: number;
  free: boolean;
  lineCount: number;
  /** Đoạn học (giây) trong video YouTube: trình phát mở đúng đoạn này */
  clipStart: number;
  clipEnd: number;
}

export interface StoryIndexItem {
  id: string;
  titles: Translations;
  level: JlptLevel;
  topic: string;
  source: "original" | "aozora-adapted";
  free: boolean;
  sentenceCount: number;
  /** Ảnh bìa chuẩn v2 (public/covers/<id>.webp); gói cũ chưa có */
  cover?: string;
  series?: { id: string; index: number };
  shelf?: StoryContent["shelf"];
  origin?: string;
  audioTrack?: AudioTrack;
}

export const VIDEO_INDEX: VideoIndexItem[] = ${JSON.stringify(videos, null, 1)};

export const STORY_INDEX: StoryIndexItem[] = ${JSON.stringify(stories, null, 1)};

export function formatDuration(sec: number): string {
  const m = Math.floor(sec / 60);
  const s = Math.round(sec % 60);
  return \`\${m}:\${String(s).padStart(2, "0")}\`;
}
`;

writeFileSync(join(root, "src/lib/catalog.generated.ts"), out);
console.log(`gen-catalog: ${videos.length} video, ${stories.length} truyện -> src/lib/catalog.generated.ts`);
